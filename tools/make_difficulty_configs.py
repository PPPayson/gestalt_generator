"""Write configs/<name>_{easy,normal,hard}.yaml from the figure list that
tools/pick_difficulty_figures.py produced (default out/difficulty_figures.yaml).

The configs share the SAME figures + seeds and differ only in closeness and contrast, so the
levels are matched on shape. Levels are given as name=closeness,contrast (default easy/normal/hard). Run each level into its own output dir:

    python3 tools/run_difficulty_set.py --name <name>
"""
import sys, pathlib, argparse, yaml
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

LEVELS_DEFAULT = ["easy=0.75,0.0", "normal=0.5,0.0", "hard=0.25,0.5"]   # name=closeness,contrast
# closeness = inducer size; contrast = bg camouflage toward object colour. normal = gen100's legacy
# radius with native colours (the pipeline default look).
HEADER = """# {name}, level "{level}": closeness {closeness}, contrast {contrast}.
# Same {n} figures (+ seeds) as the other two levels -> matched figures across easy/normal/hard.
# Each figure gets ONE catalog pair (round-robin over the 15 pairs); textures {textures};
# illusory + control per figure -> {n} x {ntex} x 2 = {total} stimuli.
# Generated by tools/make_difficulty_configs.py. Run:
#   python3 tools/run_difficulty_set.py --name {name} --levels {level}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--figures", default="out/difficulty_figures.yaml")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--levels", nargs="*", default=LEVELS_DEFAULT,
                    help="name=closeness,contrast per level (default: easy/normal/hard)")
    ap.add_argument("--textures", type=int, nargs="*", default=[0, 3])
    ap.add_argument("--name", default="varying_difficulty_benchmark_100",
                    help="set name: configs/<name>_<level>.yaml, outputs out/<name>/<level>")
    args = ap.parse_args()
    figs = yaml.safe_load(pathlib.Path(args.figures).read_text())["figures"]
    levels = {}
    for item in args.levels:
        name, vals = item.split("=")
        c, k = vals.split(",")
        levels[name] = {"closeness": float(c), "contrast": float(k)}
    for level, knobs in levels.items():
        cfg = {
            "name": f"{args.name}_{level}",
            "seed": args.seed,
            "silhouettes": [{"type": "generate",
                             "params": {"figures": figs, "closeness": knobs["closeness"]}}],
            "pairs": {"source": "catalog", "select": "distinct"},
            "dress": {"backends": ["composite"], "modes": ["perfect"],
                      "conditions": ["illusory", "control"], "contour": "auto",
                      "texture": args.textures, "contrast": knobs["contrast"],
                      "shadow": 0, "crop": True, "feather": 1.5},
            "output": {"contact_sheet": True},
        }
        body = yaml.safe_dump(cfg, sort_keys=False, default_flow_style=None, width=120)
        out = pathlib.Path("configs") / f"{args.name}_{level}.yaml"
        out.write_text(HEADER.format(level=level, name=args.name, n=len(figs), textures=args.textures,
                                     ntex=len(args.textures), total=len(figs) * 2 * len(args.textures),
                                     **knobs) + body)
        print(f"wrote {out} ({len(figs)} figures, closeness={knobs['closeness']}, contrast={knobs['contrast']})")


if __name__ == "__main__":
    main()
